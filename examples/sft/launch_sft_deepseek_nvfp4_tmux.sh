    DSA_CHUNK_SIZE="$STREAMBP_CHUNK_SIZE"
fi
if [[ -z "${APPLY_ROPE_FUSION:-}" ]]; then
    if (( CP > 1 )) || [[ "${MEGATRON_DSA_SPLIT_QK:-1}" == "1" ]]; then
        APPLY_ROPE_FUSION=0
    else
        APPLY_ROPE_FUSION=1
    fi
fi

