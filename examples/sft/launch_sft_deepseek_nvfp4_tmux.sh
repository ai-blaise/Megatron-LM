#!/usr/bin/env bash
# Launch the DeepSeek-V3.2 REAP NVFP4 SFT run in a 2x2 tmux dashboard:
#   top-left: node 0 training log      top-right: node 1 training log
#   bottom-left: node 0 GPU monitor    bottom-right: node 1 GPU monitor

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MEGATRON_DIR="${MEGATRON_DIR:-"$(cd "$SCRIPT_DIR/../.." && pwd)"}"
cd "$MEGATRON_DIR"

command -v tmux >/dev/null || {
    echo "tmux is required for this launcher" >&2
    exit 1
}

SESSION="${SESSION:-corsaire_1_research_preview}"
ATTACH="${ATTACH:-1}"
if [[ "${DRY_RUN:-0}" != "1" ]] && tmux has-session -t "$SESSION" 2>/dev/null; then
    if [[ "$ATTACH" == "1" ]]; then
        echo "tmux session '$SESSION' already exists; attaching." >&2
        exec tmux attach-session -t "$SESSION"
    fi
    echo "tmux session '$SESSION' already exists; leaving it running." >&2
    exit 0
fi

TS="${TS:-$(date -u +%Y%m%d_%H%M%S)}"
RUN_NAME="${WANDB_EXP_NAME:-corsaire-1-research-preview}"
LOG_DIR="${LOG_DIR:-"$HOME/logs"}"
LOG0="$LOG_DIR/${RUN_NAME}_node0.log"
LOG1="$LOG_DIR/${RUN_NAME}_node1.log"
mkdir -p "$LOG_DIR"

# Offline is the default for every training run. To intentionally publish live,
# set both WANDB_FORCE_OFFLINE=0 and WANDB_MODE=online at launch.
WANDB_FORCE_OFFLINE="${WANDB_FORCE_OFFLINE:-1}"
if [[ "$WANDB_FORCE_OFFLINE" == "1" ]]; then
    WANDB_MODE=offline
else
    WANDB_MODE="${WANDB_MODE:-offline}"
fi
export WANDB_FORCE_OFFLINE WANDB_MODE

MODEL_ID="${MODEL_ID:-BlaiseAI/DeepSeek-V3.2-REAP-345B-SpinQuant-ActKV-NVFP4}"
TOKENIZER_MODEL="${TOKENIZER_MODEL:-$MODEL_ID}"
LOAD_CKPT="${LOAD_CKPT:-"$HOME/checkpoints/deepseek_v32_reap_spinquant_actkv_nvfp4_megatron"}"
SAVE_CKPT="${SAVE_CKPT:-"$HOME/checkpoints/sft_deepseek_v32_reap_spinquant_actkv_nvfp4"}"

REMOTE_HOST="${REMOTE_HOST:-${NODE1_HOST:-}}"
SSH_KEY="${SSH_KEY:-}"
SSH_OPTS="${SSH_OPTS:-}"
REMOTE_MEGATRON_DIR="${REMOTE_MEGATRON_DIR:-/home/sjpat/Megatron-LM}"
REMOTE_RUNNER="${REMOTE_RUNNER:-/tmp/${RUN_NAME}_node1.sh}"

detect_master_addr() {
    if [[ -n "${MASTER_ADDR_IFNAME:-}" ]] && command -v ip >/dev/null 2>&1; then
        ip -o -4 addr show dev "$MASTER_ADDR_IFNAME" | awk '{split($4, a, "/"); print a[1]; exit}'
        return
    fi
    if command -v ip >/dev/null 2>&1; then
        local probe="${MASTER_ADDR_PROBE:-${REMOTE_HOST#*@}}"
        probe="${probe:-1.1.1.1}"
        ip -4 route get "$probe" 2>/dev/null | awk '{for (i=1; i<=NF; i++) if ($i == "src") {print $(i+1); exit}}'
        return
    fi
    hostname -I | awk '{print $1}'
}

MASTER_ADDR="${MASTER_ADDR:-$(detect_master_addr)}"
MASTER_PORT="${MASTER_PORT:-29673}"
TRITON_CACHE_DIR="${TRITON_CACHE_DIR:-"$HOME/.cache/triton/deepseek_v32_reap_sft"}"
NNODES="${NNODES:-2}"
GPUS_PER_NODE="${GPUS_PER_NODE:-8}"
TP="${TP:-4}"
PP="${PP:-4}"
CP="${CP:-1}"
EP="${EP:-4}"
ETP="${ETP:-1}"
MICRO_BATCH_SIZE="${MICRO_BATCH_SIZE:-4}"
GLOBAL_BATCH_SIZE="${GLOBAL_BATCH_SIZE:-16}"
SEQ_LENGTH="${SEQ_LENGTH:-16384}"
WORLD_SIZE=$((NNODES * GPUS_PER_NODE))
if (( NNODES != 2 )); then
    echo "This tmux wrapper currently supports exactly 2 nodes; got NNODES=$NNODES." >&2
    echo "Use examples/sft/run_sft_deepseek_nvfp4.sh directly under a scheduler for NNODES != 2." >&2
    exit 1
fi
if [[ -z "$REMOTE_HOST" ]]; then
    echo "REMOTE_HOST or NODE1_HOST must be set for the second node." >&2
    echo "Example: REMOTE_HOST=user@10.0.0.12 MASTER_ADDR=$MASTER_ADDR SESSION=$SESSION examples/sft/launch_sft_deepseek_nvfp4_tmux.sh" >&2
    exit 1
fi
SSH_CMD=(ssh)
if [[ -n "$SSH_KEY" ]]; then
    SSH_CMD+=(-i "$SSH_KEY")
fi
if [[ -n "$SSH_OPTS" ]]; then
    # shellcheck disable=SC2206
    SSH_OPT_LIST=($SSH_OPTS)
    SSH_CMD+=("${SSH_OPT_LIST[@]}")
fi
SSH_TTY_PREFIX="$(printf '%q ' "${SSH_CMD[@]}" -tt "$REMOTE_HOST")"
DENSE_MODEL_PARALLEL_SIZE=$((TP * PP * CP))
EXPERT_MODEL_PIPELINE_PARALLEL_SIZE=$((ETP * EP * PP))
if (( WORLD_SIZE % DENSE_MODEL_PARALLEL_SIZE != 0 )); then
    echo "world_size=$WORLD_SIZE must be divisible by TP*PP*CP=$DENSE_MODEL_PARALLEL_SIZE" >&2
    exit 1
fi
if (( WORLD_SIZE % EXPERT_MODEL_PIPELINE_PARALLEL_SIZE != 0 )); then
    echo "world_size=$WORLD_SIZE must be divisible by ETP*EP*PP=$EXPERT_MODEL_PIPELINE_PARALLEL_SIZE" >&2
    exit 1
fi
DP=$((WORLD_SIZE / DENSE_MODEL_PARALLEL_SIZE))
EXPERT_DP=$((WORLD_SIZE / EXPERT_MODEL_PIPELINE_PARALLEL_SIZE))
if (( GLOBAL_BATCH_SIZE % (MICRO_BATCH_SIZE * DP) != 0 )); then
    echo "GLOBAL_BATCH_SIZE=$GLOBAL_BATCH_SIZE must be divisible by MICRO_BATCH_SIZE*DP=$((MICRO_BATCH_SIZE * DP))" >&2
    exit 1
fi
GRAD_ACCUM_STEPS=$((GLOBAL_BATCH_SIZE / (MICRO_BATCH_SIZE * DP)))

round_samples_to_updates() {
    local raw_samples="$1"
    local batch_size="$2"
    echo $(( ((raw_samples + batch_size - 1) / batch_size) * batch_size ))
}

# Token-target driven default. For 16k contexts, 2B tokens is 954 updates at
# GBS=128; override TRAIN_TOKEN_TARGET or TRAIN_SAMPLES for a different run.
DATA_PATH="${DATA_PATH:-"$HOME/data/sft/blaise-sft-training-mix/blaise-sft-training-mix-full.jsonl"}"
TRAIN_TOKEN_TARGET="${TRAIN_TOKEN_TARGET:-2000000000}"
if [[ -z "${TRAIN_SAMPLES:-}" ]]; then
    RAW_TRAIN_SAMPLES=$(( (TRAIN_TOKEN_TARGET + SEQ_LENGTH - 1) / SEQ_LENGTH ))
    TRAIN_SAMPLES="$(round_samples_to_updates "$RAW_TRAIN_SAMPLES" "$GLOBAL_BATCH_SIZE")"
fi
LR_DECAY_SAMPLES="${LR_DECAY_SAMPLES:-$TRAIN_SAMPLES}"
LR_WARMUP_TOKEN_TARGET="${LR_WARMUP_TOKEN_TARGET:-$((TRAIN_TOKEN_TARGET / 20))}"
if [[ -z "${LR_WARMUP_SAMPLES:-}" ]]; then
    RAW_WARMUP_SAMPLES=$(( (LR_WARMUP_TOKEN_TARGET + SEQ_LENGTH - 1) / SEQ_LENGTH ))
    LR_WARMUP_SAMPLES="$(round_samples_to_updates "$RAW_WARMUP_SAMPLES" "$GLOBAL_BATCH_SIZE")"
fi
TRAIN_UPDATES=$((TRAIN_SAMPLES / GLOBAL_BATCH_SIZE))
TRAIN_TOKENS=$((TRAIN_SAMPLES * SEQ_LENGTH))
WARMUP_TOKENS=$((LR_WARMUP_SAMPLES * SEQ_LENGTH))
SAVE_INTERVAL="${SAVE_INTERVAL:-50}"
DECODER_FIRST_PIPELINE_NUM_LAYERS="${DECODER_FIRST_PIPELINE_NUM_LAYERS:-16}"
DECODER_LAST_PIPELINE_NUM_LAYERS="${DECODER_LAST_PIPELINE_NUM_LAYERS:-15}"
ENABLE_VPP="${ENABLE_VPP:-1}"
if [[ -z "${PIPELINE_MODEL_PARALLEL_LAYOUT:-}" ]]; then
    if [[ "$PP" -eq 4 && "$ENABLE_VPP" == "1" ]]; then
        PIPELINE_MODEL_PARALLEL_LAYOUT="Et*5|t*4|t*4|t*3|t*4|t*4|t*4|t*4|t*4|t*4|t*4|t*4|t*3|t*4|t*3|t*3L"
    elif [[ "$PP" -eq 4 ]]; then
        PIPELINE_MODEL_PARALLEL_LAYOUT="Et*16|t*15|t*15|t*15L"
    fi
fi
if [[ -z "${OVERLAP_P2P_COMM_WARMUP_FLUSH:-}" ]]; then
    if [[ "$ENABLE_VPP" == "1" ]]; then
        OVERLAP_P2P_COMM_WARMUP_FLUSH=1
    else
        OVERLAP_P2P_COMM_WARMUP_FLUSH=0
    fi
fi
OVERLAP_PARAM_GATHER="${OVERLAP_PARAM_GATHER:-0}"
# Megatron keeps checkpoints whose iteration is divisible by this value and
# deletes the previous non-retained checkpoint after a new save. Pick a value
# above the planned run so only the newest checkpoint remains.
SAVE_RETAIN_INTERVAL="${SAVE_RETAIN_INTERVAL:-100000}"
if (( SAVE_RETAIN_INTERVAL % SAVE_INTERVAL != 0 )); then
    echo "SAVE_RETAIN_INTERVAL=$SAVE_RETAIN_INTERVAL must be divisible by SAVE_INTERVAL=$SAVE_INTERVAL" >&2
    exit 1
fi
if [[ -z "${STREAMBP_LOCAL_SEQ_LENGTH:-}" ]]; then
    if [[ "${SEQUENCE_PARALLEL:-auto}" == "1" || ( "${SEQUENCE_PARALLEL:-auto}" == "auto" && "$TP" -gt 1 ) ]]; then
        STREAMBP_LOCAL_SEQ_LENGTH=$(( (SEQ_LENGTH + TP - 1) / TP ))
    else
        STREAMBP_LOCAL_SEQ_LENGTH="$SEQ_LENGTH"
    fi
fi
if [[ -z "${STREAMBP_CHUNK_SIZE:-}" ]]; then
    # StreamBP disables itself when chunk_size covers the full local sequence.
    # Default to two chunks per local sequence-parallel shard.
    STREAMBP_CHUNK_SIZE=$(( (STREAMBP_LOCAL_SEQ_LENGTH + 1) / 2 ))
fi
if [[ -z "${MEGATRON_STREAMBP_MOE_ATTENTION_BACKWARD_CHUNK_SIZE:-}" ]]; then
    MEGATRON_STREAMBP_MOE_ATTENTION_BACKWARD_CHUNK_SIZE="$STREAMBP_CHUNK_SIZE"
fi
